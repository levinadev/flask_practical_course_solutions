"""
Урок 3.1 "Маршруты и функции-представления", шаг 6

Создайте приложение `app`, в котором функция `index` отвечает текстом `Главная` сразу на двух
адресах, `/` и `/home`. А по адресу `/news/` (со слешем на конце) должна открываться страница с
текстом `Новости`.

Запускать сервер не нужно, строка `app.run()` в решении не нужна, запросы к приложению отправит
система.

Пример ввода:

    GET /

Пример вывода:

    200 Главная
"""

# Решение
from flask import Flask

app = Flask(__name__)


@app.route("/")
@app.route("/home")
def index():
    return "Главная"


@app.route("/news/")
def news():
    return "Новости"
