"""
Урок 4.3 "Обработка ошибок", шаг 4

Создайте приложение `app` со страницей `/` (текст `Главная`) и своим обработчиком ошибки 404. Он
должен отвечать текстом `Страница не найдена` с кодом 404.

Запускать сервер не нужно, строка `app.run()` в решении не нужна, запросы к приложению отправит
система.

Пример ввода:

    GET /

Пример вывода:

    200 Главная
"""

# Решение
from flask import Flask

app = Flask(__name__)


@app.route("/")
def index():
    return "Главная"


@app.errorhandler(404)
def not_found(error):
    return "Страница не найдена", 404
